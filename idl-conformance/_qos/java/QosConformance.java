// Behavioral QoS + keyed-lifecycle conformance harness for the ZeroDDS
// org.omg.dds Java PSM, run over the real DCPS (InProcessBus) pipeline.
//
// Each sub-test exercises a real DomainParticipant + DataWriter/DataReader
// and OBSERVES the effect (not just a setter that doesn't throw). Every QoS
// is built with the PolicyFactory of DDS-Java-PSM 1.0 §7.6 and handed to the
// entity factories of the specification; nothing here reaches into the
// implementation's own classes.

import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.concurrent.TimeUnit;
import org.omg.dds.core.ServiceEnvironment;
import org.omg.dds.core.policy.PolicyFactory;
import org.omg.dds.core.status.LivelinessChangedStatus;
import org.omg.dds.core.status.RequestedDeadlineMissedStatus;
import org.omg.dds.domain.DomainParticipant;
import org.omg.dds.domain.DomainParticipantFactory;
import org.omg.dds.pub.DataWriter;
import org.omg.dds.pub.DataWriterQos;
import org.omg.dds.pub.Publisher;
import org.omg.dds.sub.DataReader;
import org.omg.dds.sub.DataReaderQos;
import org.omg.dds.sub.InstanceState;
import org.omg.dds.sub.Sample;
import org.omg.dds.sub.Subscriber;
import org.omg.dds.topic.ContentFilteredTopic;
import org.omg.dds.topic.Topic;

public class QosConformance {

    // Keyed sample type: struct Reading { @key long id; long seq; double value; };
    // ZdTypes.Reading and its TypeSupport are `zerodds-idlc generate --lang
    // java Reading.idl` output, generated by build-and-run.sh on every run.
    // `createTopic(name, ZdTypes.Reading.class)` finds the generated
    // ZdTypeSupports.Support_Reading beside it.
    static ZdTypes.Reading reading(int id, int seq, double value) {
        var r = new ZdTypes.Reading();
        r.setId(id);
        r.setSeq(seq);
        r.setValue(value);
        return r;
    }

    static int domainSeq = 100;
    static int nextDomain() { return domainSeq++; }

    static int results = 0;
    static int notVerified = 0;

    static void result(String policy, String status, String detail) {
        results++;
        if (!status.equals("verified")) notVerified++;
        System.out.println("RESULT\t" + policy + "\t" + status + "\t" + detail);
    }

    static <T> List<Sample<T>> take(DataReader<T> reader) {
        return reader.take(new ArrayList<>());
    }

    static <T> List<Sample<T>> read(DataReader<T> reader) {
        return reader.read(new ArrayList<>());
    }

    /** One participant with a Reading topic, a publisher and a subscriber. */
    static final class Rig implements AutoCloseable {
        final DomainParticipant participant;
        final Topic<ZdTypes.Reading> topic;
        final Publisher publisher;
        final Subscriber subscriber;

        Rig(DomainParticipantFactory dpf, String topicName) {
            participant = dpf.createParticipant(nextDomain());
            topic = participant.createTopic(topicName, ZdTypes.Reading.class);
            publisher = participant.createPublisher();
            subscriber = participant.createSubscriber();
        }

        DataWriterQos writerQos() { return publisher.getDefaultDataWriterQos(); }

        DataReaderQos readerQos() { return subscriber.getDefaultDataReaderQos(); }

        DataWriter<ZdTypes.Reading> writer(DataWriterQos qos) {
            return publisher.createDataWriter(topic, qos);
        }

        DataReader<ZdTypes.Reading> reader(DataReaderQos qos) {
            return subscriber.createDataReader(topic, qos);
        }

        @Override
        public void close() {
            participant.close();
        }
    }

    public static void main(String[] args) throws Exception {
        // DDS-Java-PSM 1.0 §7.3.1: the implementation class is named by a system property.
        System.setProperty(ServiceEnvironment.IMPLEMENTATION_CLASS_NAME_PROPERTY,
                "org.zerodds.ServiceEnvironmentImpl");
        ServiceEnvironment env = ServiceEnvironment.createInstance(QosConformance.class.getClassLoader());
        DomainParticipantFactory dpf = DomainParticipantFactory.getInstance(env);
        PolicyFactory pf = env.getSPI().getPolicyFactory();

        // ---- 1. RELIABILITY ----------------------------------------------
        try (Rig rig = new Rig(dpf, "Rel")) {
            // KEEP_ALL on both sides: the samples are one instance, and the
            // default KEEP_LAST(1) keeps one sample per instance.
            DataReader<ZdTypes.Reading> dr = rig.reader(rig.readerQos().withPolicies(
                    pf.Reliability().withReliable(), pf.History().withKeepAll()));
            DataWriter<ZdTypes.Reading> dw = rig.writer(rig.writerQos().withPolicies(
                    pf.Reliability().withReliable(), pf.History().withKeepAll()));
            int n = 50;
            for (int i = 0; i < n; i++) dw.write(reading(1, i, i * 1.5));
            List<Sample<ZdTypes.Reading>> got = take(dr);
            boolean allInOrder = got.size() == n;
            for (int i = 0; i < got.size() && allInOrder; i++)
                if (got.get(i).getData().getSeq() != i) allInOrder = false;
            // RxO (DDS 1.4 §2.2.3.14): a RELIABLE reader does not match a
            // BEST_EFFORT writer; the reader counts the incompatibility.
            DataReader<ZdTypes.Reading> strict = rig.reader(rig.readerQos().withPolicy(
                    pf.Reliability().withReliable()));
            rig.writer(rig.writerQos().withPolicy(pf.Reliability().withBestEffort()));
            boolean rxoRejects = strict.getRequestedIncompatibleQosStatus().getTotalCount() >= 1;
            if (allInOrder && rxoRejects) {
                result("RELIABILITY", "verified",
                        "RELIABLE writer->reader delivered all " + n + " samples in seq order; "
                        + "a RELIABLE reader reports REQUESTED_INCOMPATIBLE_QOS against a BEST_EFFORT writer.");
            } else {
                result("RELIABILITY", "partial", "delivered=" + got.size()
                        + " inOrder=" + allInOrder + " rxoRejects=" + rxoRejects);
            }
        } catch (Throwable e) {
            result("RELIABILITY", "unsupported", "threw: " + e);
        }

        // ---- 2. DURABILITY (TRANSIENT_LOCAL late joiner) -----------------
        try (Rig rig = new Rig(dpf, "Dur")) {
            DataWriter<ZdTypes.Reading> dw = rig.writer(rig.writerQos().withPolicies(
                    pf.Reliability().withReliable(), pf.Durability().withTransientLocal(),
                    pf.History().withKeepLast(1)));
            dw.write(reading(1, 0, 10.0));
            dw.write(reading(1, 1, 11.0)); // KEEP_LAST(1) -> retain only seq=1
            DataReader<ZdTypes.Reading> dr = rig.reader(rig.readerQos().withPolicies(
                    pf.Reliability().withReliable(), pf.Durability().withTransientLocal(),
                    pf.History().withKeepLast(1)));
            List<Sample<ZdTypes.Reading>> got = take(dr);
            if (got.size() == 1 && got.get(0).getData().getSeq() == 1) {
                result("DURABILITY", "verified",
                        "TRANSIENT_LOCAL late joiner replayed 1 retained sample (seq="
                        + got.get(0).getData().getSeq() + "), KEEP_LAST(1) honored on the replay.");
            } else {
                result("DURABILITY", "partial", "late joiner got " + got.size() + " samples");
            }
        } catch (Throwable e) {
            result("DURABILITY", "unsupported", "threw: " + e);
        }

        // ---- 3. HISTORY KEEP_LAST(k) cap ---------------------------------
        try (Rig rig = new Rig(dpf, "Hist")) {
            DataReader<ZdTypes.Reading> dr = rig.reader(rig.readerQos().withPolicies(
                    pf.Reliability().withReliable(), pf.History().withKeepLast(1)));
            DataWriter<ZdTypes.Reading> dw = rig.writer(rig.writerQos().withPolicies(
                    pf.Reliability().withReliable(), pf.History().withKeepLast(1)));
            for (int i = 0; i < 5; i++) dw.write(reading(1, i, i));
            List<Sample<ZdTypes.Reading>> got = read(dr);
            if (got.size() == 1 && got.get(0).getData().getSeq() == 4) {
                result("HISTORY", "verified",
                        "KEEP_LAST(1) capped reader cache at 1 (got 1 of 5, retained newest seq=4).");
            } else {
                result("HISTORY", "partial",
                        "KEEP_LAST(1) reader holds " + got.size() + " of 5 same-key samples.");
            }
        } catch (Throwable e) {
            result("HISTORY", "unsupported", "threw: " + e);
        }

        // ---- 4. DEADLINE --------------------------------------------------
        try (Rig rig = new Rig(dpf, "Deadline")) {
            DataReader<ZdTypes.Reading> dr = rig.reader(rig.readerQos().withPolicy(
                    pf.Deadline().withPeriod(50, TimeUnit.MILLISECONDS)));
            DataWriter<ZdTypes.Reading> dw = rig.writer(rig.writerQos().withPolicy(
                    pf.Deadline().withPeriod(50, TimeUnit.MILLISECONDS)));
            dw.write(reading(1, 0, 1.0));
            int before = dr.getRequestedDeadlineMissedStatus().getTotalCount();
            Thread.sleep(140); // > 2 deadline periods, no new sample
            RequestedDeadlineMissedStatus st = dr.getRequestedDeadlineMissedStatus();
            if (before == 0 && st.getTotalCount() >= 1 && st.getTotalCountChange() >= 1) {
                result("DEADLINE", "verified",
                        "REQUESTED_DEADLINE_MISSED raised: totalCount=" + st.getTotalCount()
                        + " change=" + st.getTotalCountChange() + " after a missed 50ms period.");
            } else {
                result("DEADLINE", "partial",
                        "before=" + before + " total=" + st.getTotalCount()
                        + " change=" + st.getTotalCountChange());
            }
        } catch (Throwable e) {
            result("DEADLINE", "unsupported", "threw: " + e);
        }

        // ---- 5. LIVELINESS ------------------------------------------------
        try (Rig rig = new Rig(dpf, "Liveliness")) {
            // MANUAL_BY_TOPIC with a 300 ms lease: the writer is alive when it
            // is created and loses its liveliness when the lease runs out
            // without a write or an assert_liveliness (DDS 1.4 §2.2.3.11).
            DataReader<ZdTypes.Reading> dr = rig.reader(rig.readerQos().withPolicy(
                    pf.Liveliness().withManualByTopic().withLeaseDuration(300, TimeUnit.MILLISECONDS)));
            rig.writer(rig.writerQos().withPolicy(
                    pf.Liveliness().withManualByTopic().withLeaseDuration(300, TimeUnit.MILLISECONDS)));
            LivelinessChangedStatus alive = dr.getLivelinessChangedStatus();
            LivelinessChangedStatus lost;
            long end = System.nanoTime() + TimeUnit.SECONDS.toNanos(5);
            do {
                Thread.sleep(25);
                lost = dr.getLivelinessChangedStatus();
            } while (lost.getNotAliveCount() == 0 && System.nanoTime() < end);
            if (alive.getAliveCount() == 1 && lost.getNotAliveCount() == 1
                    && lost.getAliveCountChange() == -1 && lost.getNotAliveCountChange() == 1) {
                result("LIVELINESS", "verified",
                        "LIVELINESS_CHANGED observed alive=1 -> notAlive=1 (aliveChange=-1, notAliveChange=1) "
                        + "after the 300ms MANUAL_BY_TOPIC lease ran out.");
            } else {
                result("LIVELINESS", "partial",
                        "alive=" + alive.getAliveCount() + " notAlive=" + lost.getNotAliveCount()
                        + " aliveChange=" + lost.getAliveCountChange()
                        + " notAliveChange=" + lost.getNotAliveCountChange());
            }
        } catch (Throwable e) {
            result("LIVELINESS", "unsupported", "threw: " + e);
        }

        // ---- 6. OWNERSHIP (EXCLUSIVE strength arbitration) ----------------
        try (Rig rig = new Rig(dpf, "Own")) {
            DataReader<ZdTypes.Reading> dr = rig.reader(rig.readerQos().withPolicies(
                    pf.Ownership().withExclusive(), pf.History().withKeepAll()));
            DataWriter<ZdTypes.Reading> dwLow = rig.writer(rig.writerQos().withPolicies(
                    pf.Ownership().withExclusive(), pf.OwnershipStrength().withValue(1)));
            DataWriter<ZdTypes.Reading> dwHigh = rig.writer(rig.writerQos().withPolicies(
                    pf.Ownership().withExclusive(), pf.OwnershipStrength().withValue(10)));
            dwHigh.write(reading(1, 0, 100.0)); // owner
            dwLow.write(reading(1, 1, 1.0));     // filtered out
            dwHigh.write(reading(1, 2, 102.0));
            List<Sample<ZdTypes.Reading>> got = take(dr);
            boolean onlyOwner = got.size() == 2
                    && got.stream().allMatch(s -> s.getData().getValue() >= 100.0);
            if (onlyOwner) {
                result("OWNERSHIP", "verified",
                        "EXCLUSIVE arbitration: only highest-strength (10) writer delivered; "
                        + "lower-strength (1) sample on the same key was filtered (got " + got.size() + ").");
            } else {
                result("OWNERSHIP", "partial", "got " + got.size() + " samples (expected 2 from owner)");
            }
        } catch (Throwable e) {
            result("OWNERSHIP", "unsupported", "threw: " + e);
        }

        // ---- 7. PARTITION -------------------------------------------------
        try (Rig rig = new Rig(dpf, "Part")) {
            Publisher pubA = rig.participant.createPublisher(rig.participant.getDefaultPublisherQos()
                    .withPolicy(pf.Partition().withName(Collections.singletonList("A"))));
            Subscriber subB = rig.participant.createSubscriber(rig.participant.getDefaultSubscriberQos()
                    .withPolicy(pf.Partition().withName(Collections.singletonList("B"))));
            Subscriber subA = rig.participant.createSubscriber(rig.participant.getDefaultSubscriberQos()
                    .withPolicy(pf.Partition().withName(Collections.singletonList("A"))));
            // Non-overlapping partitions must NOT communicate.
            DataReader<ZdTypes.Reading> drB = subB.createDataReader(rig.topic);
            DataWriter<ZdTypes.Reading> dwA = pubA.createDataWriter(rig.topic);
            dwA.write(reading(1, 0, 1.0));
            int isolated = take(drB).size();
            // Overlapping partitions DO communicate.
            DataReader<ZdTypes.Reading> drA = subA.createDataReader(rig.topic);
            dwA.write(reading(2, 0, 2.0));
            int matched = take(drA).size();
            if (isolated == 0 && matched == 1) {
                result("PARTITION", "verified",
                        "Partition isolation enforced: A->B delivered 0; A->A delivered 1.");
            } else {
                result("PARTITION", "partial", "isolated=" + isolated + " matched=" + matched);
            }
        } catch (Throwable e) {
            result("PARTITION", "unsupported", "threw: " + e);
        }

        // ---- 8. CONTENT-FILTERED-TOPIC -----------------------------------
        try (Rig rig = new Rig(dpf, "Cft")) {
            ContentFilteredTopic<ZdTypes.Reading> cft = rig.participant.createContentFilteredTopic(
                    "HighValue", rig.topic, "value > 50.0", Collections.emptyList());
            DataReader<ZdTypes.Reading> dr = rig.subscriber.createDataReader(cft);
            DataWriter<ZdTypes.Reading> dw = rig.publisher.createDataWriter(rig.topic);
            dw.write(reading(1, 0, 10.0));  // dropped
            dw.write(reading(2, 1, 99.0));  // kept
            dw.write(reading(3, 2, 5.0));   // dropped
            List<Sample<ZdTypes.Reading>> got = take(dr);
            if (got.size() == 1 && got.get(0).getData().getValue() == 99.0) {
                result("CONTENT_FILTER", "verified",
                        "ContentFilteredTopic 'value > 50.0' delivered only the matching sample (1 of 3).");
            } else {
                result("CONTENT_FILTER", "partial", "got " + got.size() + " samples (expected 1)");
            }
        } catch (Throwable e) {
            result("CONTENT_FILTER", "unsupported", "threw: " + e);
        }

        // ---- 9. KEYED LIFECYCLE (dispose / unregister / instance_state) ---
        try (Rig rig = new Rig(dpf, "Life")) {
            DataReader<ZdTypes.Reading> dr = rig.reader(rig.readerQos().withPolicy(
                    pf.History().withKeepAll()));
            // autodispose_unregistered_instances is TRUE by default (DDS 1.4
            // §2.2.3.21): an unregister would dispose as well, and the reader
            // would see NOT_ALIVE_DISPOSED for key 2 too.
            DataWriter<ZdTypes.Reading> dw = rig.writer(rig.writerQos().withPolicy(
                    pf.WriterDataLifecycle().withAutDisposeUnregisteredInstances(false)));

            dw.write(reading(1, 0, 1.0));
            dw.write(reading(2, 0, 2.0));
            dw.dispose(dw.lookupInstance(reading(1, 0, 0.0)));           // key 1 -> DISPOSED
            dw.unregisterInstance(dw.lookupInstance(reading(2, 0, 0.0))); // key 2 -> NO_WRITERS
            List<Sample<ZdTypes.Reading>> got = take(dr);
            boolean sawDisposed = got.stream().anyMatch(
                    s -> s.getInstanceState() == InstanceState.NOT_ALIVE_DISPOSED);
            boolean sawNoWriters = got.stream().anyMatch(
                    s -> s.getInstanceState() == InstanceState.NOT_ALIVE_NO_WRITERS);
            if (sawDisposed && sawNoWriters) {
                result("KEYED_LIFECYCLE", "verified",
                        "dispose(key1)->NOT_ALIVE_DISPOSED and unregister(key2)->NOT_ALIVE_NO_WRITERS "
                        + "both observed on the reader via Sample.getInstanceState().");
            } else {
                result("KEYED_LIFECYCLE", "partial",
                        "disposed=" + sawDisposed + " noWriters=" + sawNoWriters);
            }
        } catch (Throwable e) {
            result("KEYED_LIFECYCLE", "unsupported", "threw: " + e);
        }

        System.out.println("HARNESS_DONE");
        if (results != 9 || notVerified != 0) {
            System.out.println(notVerified + " of " + results + " QoS checks not verified");
            System.exit(1);
        }
        System.out.println("ALL " + results + " QOS CHECKS VERIFIED");
    }
}
