#!/usr/bin/env bash
# Tier-2 conformance gate: every ZeroDDS language binding must reproduce the SINGLE
# golden wire (goldens/<feature>.golden.bin) byte-for-byte, and decode it back to
# the canonical values. The wire is the wire — there is no per-language golden.
#
# For each language L and feature F (the eleven types of features.idl, and
# combo::Telemetry of combo.idl as the feature `combo`):
#   (1) L.encode(canonical(F))  ==  goldens/F.golden.bin   (byte-identical)
#   (2) L.decode(goldens/F.golden.bin)  ==  canonical(F)
#
# Then each column decodes proofs/endianness's goldens — the Rust column's
# encodings of seven of the features in XCDR2 and XCDR1, little- and
# big-endian: every column the XCDR2 big-endian ones, and C, C++, Python and
# TypeScript the XCDR1 ones too, with the codec generated for
# `--encoding xcdr1`.
#
# Every column generates its codecs from features.idl and combo.idl on every
# run. The per-language *.<lang>.bin files are EPHEMERAL (git-ignored); only
# *.golden.bin is committed. The Rust column writes the goldens, so run it
# first — a run of other languages alone compares against the committed ones.
#
# Usage: ./verify.sh            # build+run every language, cmp all vs golden
#        ./verify.sh "<lang>..." # the named languages only
set -uo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
REPO="$(cd "$HERE/../../.." && pwd)"
G="$HERE/goldens"
FEATS="wstr mut bits tree arr prim mutnest outerkey mapenum mapprim fixed"
ALL="$FEATS combo"
fail=0

IDLC="${CARGO_TARGET_DIR:-$REPO/target}/debug/zerodds-idlc"
# The generator every language's codec comes from, built once. A step that
# fails stops that language: its output is not silenced, and `fresh` removes
# the language's bins first, so a run that produced nothing cannot compare
# the bins an earlier run left behind.
( cd "$REPO" && cargo build -q -p zerodds-idlc ) || { echo "zerodds-idlc does not build"; exit 1; }
gen() { # <lang> <outdir> [idl, default features.idl]
  "$IDLC" generate --lang "$1" "$HERE/${3:-features.idl}" --out "$2"
}
fresh() { rm -f "$G"/*."$1".bin; }
# The same features.idl under XCDR1, for the second stage below.
gen_x1() { # <lang> <outdir>
  "$IDLC" generate --lang "$1" "$HERE/features.idl" --out "$2" --encoding xcdr1
}

cmp_all() { # <lang>  — diff every ephemeral <feat>.<lang>.bin against the golden
  local lang=$1 f
  for f in $ALL; do
    if cmp -s "$G/$f.$lang.bin" "$G/$f.golden.bin"; then
      echo "  [$lang] $f  encode == golden"
    else
      echo "  [$lang] $f  ENCODE != GOLDEN  ($(wc -c <"$G/$f.$lang.bin" 2>/dev/null|tr -d ' ')B vs $(wc -c <"$G/$f.golden.bin"|tr -d ' ')B)"
      fail=1
    fi
  done
}

run_rust() { # the goldens: rust-features' codec, generated by zerodds-build
  fresh rust
  ( cd "$HERE/rust-features" && cargo run -q ) || return 1   # writes goldens/<feat>.rust.bin
  ( cd "$HERE/rust" && cargo run -q -- ENCODE "$G/combo.rust.bin" >/dev/null ) || return 1
  for f in $ALL; do cp "$G/$f.rust.bin" "$G/$f.golden.bin"; done
  ( cd "$HERE/rust" && cargo run -q -- DECODE "$G/combo.golden.bin" >/dev/null ) || return 1
  cmp_all rust
}

run_cpp() {
  fresh cpp
  ( cd "$HERE/cpp"
    gen c++ gen_feat || exit 1
    make -s -C "$REPO/runtime/cpp" build/libzerodds_wire.a || exit 1
    c++ -std=c++17 -Wall -I. -I"$REPO/crates/cpp/include" -I"$REPO/runtime/cpp/include" \
      features_interop.cpp "$REPO/runtime/cpp/build/libzerodds_wire.a" -o features_interop || exit 1
    local f; for f in $FEATS; do ./features_interop $f ENCODE "$G/$f.cpp.bin" >/dev/null || exit 1; done
    for f in $FEATS; do ./features_interop $f DECODE "$G/$f.golden.bin" >/dev/null || { echo "  [cpp] $f DECODE of the golden FAILED"; exit 1; }; done
    gen c++ gen_combo combo.idl || exit 1
    c++ -std=c++17 -Wall -I. -I"$REPO/crates/cpp/include" -I"$REPO/runtime/cpp/include" \
      combo_interop.cpp "$REPO/runtime/cpp/build/libzerodds_wire.a" -o combo_interop || exit 1
    ./combo_interop ENCODE "$G/combo.cpp.bin" >/dev/null || exit 1
    ./combo_interop DECODE "$G/combo.golden.bin" >/dev/null || { echo "  [cpp] combo DECODE of the golden FAILED"; exit 1; }
    ./features_interop - BE >/dev/null || { echo "  [cpp] BE decode FAILED"; exit 1; }
    gen_x1 c++ gen_x1 || exit 1
    c++ -std=c++17 -Wall -DFEATURES_XCDR1 -I. -I"$REPO/crates/cpp/include" -I"$REPO/runtime/cpp/include" \
      features_interop.cpp "$REPO/runtime/cpp/build/libzerodds_wire.a" -o features_interop_x1 || exit 1
    ./features_interop_x1 - XCDR1 >/dev/null || { echo "  [cpp] XCDR1 decode FAILED"; exit 1; }
    echo "  [cpp] xcdr2-be, xcdr1-le, xcdr1-be decode == canonical" ) || return 1
  cmp_all cpp
}

run_c() {
  fresh c
  ( cd "$HERE/c"
    gen c gen_feat || exit 1
    make -s -C "$REPO/runtime/c" || exit 1
    cc -std=c11 -Wall -I. -I"$REPO/runtime/c/include" features_interop.c \
      "$REPO/runtime/c/build/libzerodds_wire.a" -o features_interop || exit 1
    local f; for f in $FEATS; do ./features_interop $f ENCODE "$G/$f.c.bin" >/dev/null || exit 1; done
    for f in $FEATS; do ./features_interop $f DECODE "$G/$f.golden.bin" >/dev/null || { echo "  [c] $f DECODE of the golden FAILED"; exit 1; }; done
    gen c gen_combo combo.idl || exit 1
    cc -std=c11 -Wall -I. -I"$REPO/runtime/c/include" interop.c \
      "$REPO/runtime/c/build/libzerodds_wire.a" -o interop || exit 1
    ./interop ENCODE "$G/combo.c.bin" >/dev/null || exit 1
    ./interop DECODE "$G/combo.golden.bin" >/dev/null || { echo "  [c] combo DECODE of the golden FAILED"; exit 1; }
    ./features_interop - BE >/dev/null || { echo "  [c] BE decode FAILED"; exit 1; }
    gen_x1 c gen_x1 || exit 1
    cc -std=c11 -Wall -DFEATURES_XCDR1 -I. -I"$REPO/runtime/c/include" features_interop.c \
      "$REPO/runtime/c/build/libzerodds_wire.a" -o features_interop_x1 || exit 1
    ./features_interop_x1 - XCDR1 >/dev/null || { echo "  [c] XCDR1 decode FAILED"; exit 1; }
    echo "  [c] xcdr2-be, xcdr1-le, xcdr1-be decode == canonical" ) || return 1
  cmp_all c
}

run_python() {
  fresh python
  ( cd "$HERE/python"
    gen python . || exit 1
    PYTHONPATH="$REPO/runtime/python${PYTHONPATH:+:$PYTHONPATH}" python3 features_interop.py ENCODE >/dev/null || exit 1
    PYTHONPATH="$REPO/runtime/python${PYTHONPATH:+:$PYTHONPATH}" python3 features_interop.py DECODE >/dev/null || exit 1
    gen python . combo.idl || exit 1
    PYTHONPATH="$REPO/runtime/python${PYTHONPATH:+:$PYTHONPATH}" python3 interop.py ENCODE "$G/combo.python.bin" >/dev/null || exit 1
    PYTHONPATH="$REPO/runtime/python${PYTHONPATH:+:$PYTHONPATH}" python3 interop.py DECODE "$G/combo.golden.bin" >/dev/null || exit 1
    gen_x1 python x1 || exit 1
    PYTHONPATH="$REPO/runtime/python${PYTHONPATH:+:$PYTHONPATH}" python3 features_interop.py REPRESENTATIONS >/dev/null || { echo "  [python] REPRESENTATIONS decode FAILED"; exit 1; }
    echo "  [python] xcdr2-be, xcdr1-le, xcdr1-be decode == canonical" ) || return 1
  cmp_all python
}

run_ts() {
  fresh ts
  ( cd "$HERE/ts"
    gen typescript gen || exit 1
    mv gen/features.ts gen/30_features.ts
    npm run -s encode:features >/dev/null || exit 1
    npm run -s decode:features >/dev/null || exit 1
    gen typescript gen combo.idl || exit 1
    npm run -s encode -- "$G/combo.ts.bin" >/dev/null || exit 1
    npm run -s decode -- "$G/combo.golden.bin" >/dev/null || exit 1
    gen_x1 typescript gen-x1 || exit 1
    npm run -s be:features >/dev/null || { echo "  [ts] BE decode FAILED"; exit 1; }
    npm run -s xcdr1:features >/dev/null || { echo "  [ts] XCDR1 decode FAILED"; exit 1; }
    echo "  [ts] xcdr2-be, xcdr1-le, xcdr1-be decode == canonical" ) || return 1
  cmp_all ts
}

run_java() {
  fresh java
  ( cd "$HERE/java"
    ./build.sh FeaturesInterop ../features.idl ENCODE >/dev/null || exit 1
    ./build.sh FeaturesInterop ../features.idl DECODE >/dev/null || exit 1
    ./build.sh FeaturesInterop ../features.idl BE >/dev/null || { echo "  [java] BE decode FAILED"; exit 1; }
    echo "  [java] xcdr2-be decode == canonical"
    ./build.sh Interop ../combo.idl ENCODE "$G/combo.java.bin" >/dev/null || exit 1
    ./build.sh Interop ../combo.idl DECODE "$G/combo.golden.bin" >/dev/null || exit 1 ) || return 1
  cmp_all java
}

run_csharp() {
  fresh csharp
  ( cd "$HERE/csharp-features"
    gen csharp . || exit 1
    rm -rf obj bin   # a clean build: an incremental one may keep a stale features.cs
    dotnet build -v q --nologo || exit 1
    dll="$(find bin -name 'interop-csharp-features.dll' | head -1)"
    dotnet "$dll" ENCODE >/dev/null || exit 1
    dotnet "$dll" DECODE >/dev/null || exit 1
    dotnet "$dll" BE >/dev/null || { echo "  [csharp] BE decode FAILED"; exit 1; }
    echo "  [csharp] xcdr2-be decode == canonical" ) || return 1
  ( cd "$HERE/csharp"
    gen csharp . combo.idl || exit 1
    rm -rf obj bin
    dotnet build -v q --nologo || exit 1
    dll="$(find bin -name 'interop-csharp.dll' | head -1)"
    dotnet "$dll" ENCODE "$G/combo.csharp.bin" >/dev/null || exit 1
    dotnet "$dll" DECODE "$G/combo.golden.bin" >/dev/null || exit 1 ) || return 1
  cmp_all csharp
}

LANGS="${1:-rust cpp c python ts java csharp}"
for L in $LANGS; do
  echo "== $L =="
  run_$L || { echo "  [$L] build/run FAILED"; fail=1; }
done
[ $fail -eq 0 ] && echo "ALL LANGUAGES CONFORM TO THE GOLDEN" || echo "CONFORMANCE FAILURES ABOVE"
exit $fail
